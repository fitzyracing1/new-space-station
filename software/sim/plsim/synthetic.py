"""Generates a SYNTHETIC shadow-mode scenario. Nothing here is real ISS or Ping Lite data.

Timeline (simulated seconds):
  0      crew aboard, nominal; 92-min orbits with ~36-min eclipses (synthetic)
  3600   crew departs (uncrewed operations begin)
  1800   CO2 excursion for 10 min while crewed (synthetic fault)
  9000   comm loss for 25 min  -> expect UNCREWED_AUTONOMOUS, then AOS
  12000  RH sensor fails implausible -> expect sensor fault, not alarm
  14400  slow leak starts (~2 kg/day equivalent) -> expect LEAK, then SAFE_HOLD
  30000  ground acknowledgement while AOS; leak persists so SAFE_HOLD re-latches
EDAC counters tick, one processor reset at 20000 s, one uncorrected upset at 25000 s.
"""
import math
import random

HEADER = "# SYNTHETIC DATA - generated by plsim.synthetic, not real telemetry\n"


def generate(duration_s=32000, step_s=60, seed=7):
    rnd = random.Random(seed)
    rows = []
    p = 101.3
    corr, uncorr, boot = 1000, 0, 1
    leak_kpa_s = -(2.0 / 86400.0) * 8.314 * 295.15 / (560.0 * 0.02897) / 1000.0
    for t in range(0, duration_s + 1, step_s):
        crew = 1 if t < 3600 else 0
        phase = (t % 5520) / 5520.0
        eclipse = 1 if phase > 0.61 else 0
        ppco2 = 0.30 + rnd.gauss(0, 0.01) + (0.45 if 1800 <= t < 2400 else 0.0)
        ppo2 = 21.3 + rnd.gauss(0, 0.05)
        if t >= 14400:
            p += leak_kpa_s * step_s
        rh = 45 + rnd.gauss(0, 1.0)
        valid = 0x1F
        if 12000 <= t < 12600:
            rh = 250.0  # failed sensor
        temp = 22.0 + 0.5 * math.sin(2 * math.pi * phase) + rnd.gauss(0, 0.05)
        rows.append(f"E,{t},{valid},{ppo2:.3f},{ppco2:.3f},{p + rnd.gauss(0, 0.002):.4f},{rh:.1f},{temp:.2f}")
        array_w = 0.0 if eclipse else 70000.0
        soc = 90.0 - 25.0 * (phase - 0.61) / 0.39 if eclipse else 90.0
        rows.append(f"P,{t},{eclipse},{array_w:.0f},{soc:.1f},{temp:.2f}")
        aos = 0 if 9000 <= t < 10500 else 1
        rows.append(f"O,{t},{crew},{aos}")
        corr += rnd.choice([0, 0, 0, 1])
        if t == 20000 - 20000 % step_s:
            boot += 1
            corr, uncorr = 0, 0
        if t == 25000 - 25000 % step_s:
            uncorr += 1
        rows.append(f"T,{t},{corr},{uncorr},{boot}")
        if t == 30000 - 30000 % step_s:
            rows.append(f"A,{t}")
    return HEADER + "\n".join(rows) + "\n"


if __name__ == "__main__":
    import argparse
    import sys
    ap = argparse.ArgumentParser()
    ap.add_argument("--step", type=int, default=60, help="sample period, s")
    sys.stdout.write(generate(step_s=ap.parse_args().step))
